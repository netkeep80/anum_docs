import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { loadReaderG42 } from "../src/tooling/mts-reader-g42.js";
import { renderReaderR43Preview } from "../src/tooling/mts-reader-r43.js";
import { READER_R44_W1_PATH,loadReaderR44W1,parseReaderR44W1,renderReaderR44W1Preview } from "../src/tooling/mts-reader-r44.js";
const root=resolve("..");
const input=readFileSync(resolve(root,READER_R44_W1_PATH),"utf8");
const m=loadReaderR44W1(root),before=renderReaderR43Preview(root),after=renderReaderR44W1Preview(root);
assert.equal(m.publication,"blocked");
assert.equal(m.reviews.length,4);
assert.equal(loadReaderG42(root).order.length,119);
assert.equal((after.match(/^\*\*(?:g4:|g7:|g8:|g10:|g11:|basis:|concept:|editorial:)/gm)??[]).length,119);
assert.equal((after.match(/^## /gm)??[]).length,(before.match(/^## /gm)??[]).length+1);
assert.ok(after.includes("implicitPairAssociativity=NONE"));
assert.ok(after.includes("A⟼B⟼C"));
assert.ok(after.includes("(A⟼B)⟼C"));
assert.ok(after.includes("A⟼(B⟼C)"));
assert.ok(!loadReaderG42(root).chapters.find(c=>c.id==="grammar-and-historical-mp")!.scopeRu.includes("неявная алгебраическая ассоциативность"));
assert.ok(after.includes("813a1569300b241a3b70eb282eecd8231db15e4b")===false);
assert.ok(after.includes("7 октября 2026 года в 23:17:15 UTC"));
assert.ok(after.includes("PR #2078"));
assert.ok(after.includes("FRM-04 — PROVED_UNDER_EXACT_SEQUENCE_INJECTIVITY"));
assert.ok(after.includes("нет")===true || after.includes("не следует"));
for (const c of m.reviews) assert.ok(after.includes("**"+c.id+" / "+c.finding));
assert.ok(after.includes("ПУБЛИКАЦИЯ ЗАБЛОКИРОВАНА"));
assert.ok(after.includes("не заменяет независимую научную проверку всех 119"));
const p=(v:string)=>parseReaderR44W1(v,root);
assert.throws(()=>p(input.replace("author_approval: not-recorded","author_approval: approved")),/cannot self-approve/);
assert.throws(()=>p(input.replace("publication: blocked","publication: ready")),/cannot self-approve/);
assert.throws(()=>p(input.replace("scientific_coverage: targeted-first-wave-not-119-full-review","scientific_coverage: 119-science-proved")),/cannot self-approve/);
assert.throws(()=>p(input.replace("accepted_value: NONE","accepted_value: LEFT")),/version authority lost/);
assert.throws(()=>p(input.replace("decision: ACCEPT_MTS_V0_15","decision: REVIEW_PENDING")),/historical v0.15 acceptance provenance drift/);
assert.throws(()=>p(input.replace("state: corrected-in-proposed-G42-only","state: accepted")),/review cannot self-promote/);
assert.throws(()=>p(input.replace("open: [R40-06","open: [R40-07")),/remaining R40 may not close/);
assert.throws(()=>p(input+"\npublication: ready\n"),/malformed\/duplicate YAML/);
console.log("R44-W1: v0.14 grammar NONE versus v0.15 DSA, author ACCEPT/merge evidence, conditional FRM-03/04/07, 119 source-atom retention, four bounded independent reviews; no scientific acceptance.");
